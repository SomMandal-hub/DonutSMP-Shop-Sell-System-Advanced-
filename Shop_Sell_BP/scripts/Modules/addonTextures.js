/**
 * Reverse lookup: minecraft item ID → addon texture path
 * Built automatically from addonTextures by stripping
 * "textures/items/" or "textures/blocks/" and mapping back.
 * 
 * e.g. 'textures/items/acacia_chest_boat'
 *   → 'minecraft:acacia_chest_boat' : 'textures/items/acacia_chest_boat'
 */
export const addonTextureById = new Map(
    [...addonTextures].map(path => {
        const id = 'minecraft:' + path
            .replace('textures/items/', '')
            .replace('textures/blocks/', '')
        return [id, path]
    })
)

